/**
 * RFC 7807 / RFC 9457 Problem Details for HTTP APIs (#946).
 *
 * Provides a standardized problem-details representation with stable machine codes,
 * human-readable safe details, category categorization, and actionable remediation hints.
 */

import { ERROR_CODES, type ErrorCode } from "./constants.js";
import { describeError, toUserSafeError, type ErrorCategory } from "./errorTaxonomy.js";

export const PROBLEM_DETAILS_CONTENT_TYPE = "application/problem+json";
export const PROBLEM_TYPE_BASE_URI = "https://api.vaultquest.io/errors";

export interface InvalidParam {
  name: string;
  reason: string;
}

export interface ProblemDetails {
  /** A URI reference that identifies the problem type. */
  type: string;
  /** A short, human-readable summary of the problem type. */
  title: string;
  /** The HTTP status code generated by the origin server. */
  status: number;
  /** A human-readable explanation specific to this occurrence of the problem. */
  detail: string;
  /** A URI reference that identifies the specific occurrence of the problem. */
  instance: string;
  /** Stable machine error code (e.g. VAULT_INVALID_AMOUNT). */
  code: string;
  /** Error category for machine grouping. */
  category: ErrorCategory;
  /** Whether the request can be safely retried without changes. */
  retryable: boolean;
  /** Actionable next step or remediation hint for the client or operator. */
  remediation?: string;
  /** Correlation identifier for distributed tracing. */
  error_id: string;
  /** ISO-8601 timestamp of when the error was produced. */
  timestamp: string;
  /** Parameter-level validation failures when applicable. */
  invalid_params?: InvalidParam[];
  /** Additional non-sensitive structured details. */
  details?: unknown;
}

export interface FormatProblemDetailsOptions {
  message?: string;
  instance?: string;
  errorId: string;
  details?: unknown;
  issues?: unknown;
  timestamp?: string;
}

const CATEGORY_TITLES: Record<ErrorCategory, string> = {
  validation: "Validation Error",
  authorization: "Authorization Error",
  not_found: "Resource Not Found",
  conflict: "State Conflict Error",
  rate_limit: "Rate Limit Exceeded",
  wallet: "Wallet Error",
  settlement: "Settlement Error",
  dependency: "Upstream Dependency Error",
  internal: "Internal Server Error"
};

/**
 * Extracts normalized parameter issues into RFC invalid_params.
 */
export function extractInvalidParams(issues: unknown): InvalidParam[] | undefined {
  if (!Array.isArray(issues) || issues.length === 0) return undefined;
  const params: InvalidParam[] = [];
  for (const issue of issues) {
    if (typeof issue === "object" && issue !== null) {
      const path = Array.isArray((issue as any).path) ? (issue as any).path.join(".") : (issue as any).path;
      const message = (issue as any).message || "Invalid parameter value";
      params.push({
        name: String(path || "parameter"),
        reason: String(message)
      });
    }
  }
  return params.length > 0 ? params : undefined;
}

/**
 * Formats an error into an RFC 7807/9457 Problem Details object.
 */
export function formatProblemDetails(
  code: string,
  statusCode: number,
  opts: FormatProblemDetailsOptions
): ProblemDetails {
  const safe = toUserSafeError(code, statusCode, opts.message);
  const descriptor = describeError(code);
  const title = CATEGORY_TITLES[safe.category] || "API Problem";
  const typeUri = `${PROBLEM_TYPE_BASE_URI}/${safe.code}`;
  const instanceUri = opts.instance || `/errors/${safe.code}/${opts.errorId}`;
  const invalidParams = extractInvalidParams(opts.issues);

  return {
    type: typeUri,
    title,
    status: statusCode,
    detail: safe.message,
    instance: instanceUri,
    code: safe.code,
    category: safe.category,
    retryable: safe.retryable,
    ...(safe.recovery ? { remediation: safe.recovery } : {}),
    error_id: opts.errorId,
    timestamp: opts.timestamp || new Date().toISOString(),
    ...(invalidParams ? { invalid_params: invalidParams } : {}),
    ...(opts.details !== undefined ? { details: opts.details } : {})
  };
}
